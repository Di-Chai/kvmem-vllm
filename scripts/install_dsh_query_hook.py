#!/usr/bin/env python3
"""Install the Query onPayload hook into the isolated, stopped cloud DSH.

The default route preserves the existing local deployment. For a new route pass
all of --provider, --model, and --base-url. --dry-run validates without writing.
Only the task-owned cloud harness is accepted; this never patches a user's DSH.
No model request, package installation, or service startup is performed.
"""
from __future__ import annotations

import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import tempfile
from urllib.parse import urlsplit

ALLOWED_HARNESS_ROOT = Path("/root/data/kvmem-vllm-gc/dsh-harness")
EXPECTED_ADAPTER_SHA256 = "af5bec01ae8ac4c1ea1c9e27010148463bcb2b49ba0caf351adbb546453051f9"
EXPECTED_ADAPTER_VERSION = "0.1.0-rc.8"
EXPECTED_CLI_VERSION = "0.1.0-rc.7"
DEFAULT_ROUTE = {
    "provider": "kvmem-main-dflash2-continuation",
    "model": "kvmem-dsh-dflash2",
    "baseURL": "http://127.0.0.1:18385/v1",
}
HOOK_SOURCE = Path(__file__).with_name("dsh_query_epoch.mjs")
STATE_NAME = ".kvmem-query-hook.json"
BACKUP_NAME = ".kvmem-query-hook.original.js"
HOOK_NAME = "kvmem-query-epoch.mjs"
WRAPPER_NAME = "kvmem-query-hook.mjs"


def digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def normalize_route(route: dict) -> dict[str, str]:
    if not isinstance(route, dict):
        raise ValueError("Query route must be an object")
    result = {}
    for field in ("provider", "model", "baseURL"):
        value = route.get(field)
        if (not isinstance(value, str) or not value or value != value.strip()
                or any(ord(c) < 32 or ord(c) == 127 for c in value)):
            raise ValueError(f"Query route requires a nonempty {field}")
        result[field] = value
    try:
        endpoint = urlsplit(result["baseURL"])
        endpoint.port  # Validate malformed/out-of-range ports.
    except ValueError as exc:
        raise ValueError("baseURL must be an absolute HTTP(S) URL") from exc
    if (endpoint.scheme not in ("http", "https") or not endpoint.hostname
            or endpoint.username is not None or endpoint.password is not None
            or endpoint.query or endpoint.fragment or "\\" in result["baseURL"]):
        raise ValueError("baseURL must be HTTP(S), without credentials, query, or fragment")
    result["baseURL"] = result["baseURL"].rstrip("/")
    return result


def owned(path: Path, root: Path) -> Path:
    resolved = path.resolve()
    if not resolved.is_relative_to(root):
        raise ValueError(f"Refusing a path outside the isolated harness: {path}")
    return resolved


def plain_file(path: Path) -> None:
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise ValueError(f"Refusing a non-regular file: {path}")


def manifest(path: Path, name: str, version: str, root: Path) -> None:
    owned(path, root)
    data = json.loads(path.read_text())
    if data.get("name") != name or data.get("version") != version:
        raise ValueError(f"Unsupported package: expected {name}@{version}")


def find_adapter(root: Path) -> Path:
    manifest(root / "node_modules/@deepseek-ai/dsh/package.json",
             "@deepseek-ai/dsh", EXPECTED_CLI_VERSION, root)
    candidates = [
        root / "node_modules/.pnpm/node_modules/@deepseek-ai/dsh-llm-pi-ai",
        root / "node_modules/@deepseek-ai/dsh/node_modules/@deepseek-ai/dsh-llm-pi-ai",
        root / "node_modules/@deepseek-ai/dsh-llm-pi-ai",
    ]
    found = {owned(p, root) for p in candidates if p.exists()}
    if len(found) != 1:
        raise ValueError("Expected exactly one installed dsh-llm-pi-ai package")
    package = found.pop()
    manifest(package / "package.json", "@deepseek-ai/dsh-llm-pi-ai",
             EXPECTED_ADAPTER_VERSION, root)
    lib = owned(package / "lib", root)
    if not lib.is_dir():
        raise ValueError("Adapter lib directory is missing")
    index = lib / "index.js"
    plain_file(index)
    if not index.is_file():
        raise ValueError("Adapter index.js is missing")
    return index


def patch_adapter(original: bytes) -> bytes:
    text = original.decode("utf-8")
    needle = "headers: requestHeaders(profile.headers)"
    lines = [line for line in text.splitlines() if line.strip() == needle]
    if text.count(needle) != 1 or len(lines) != 1:
        raise ValueError("The verified adapter no longer has the expected onPayload seam")
    indent = re.match(r"\s*", lines[0]).group()
    patched = text.replace(needle, needle + ",\n" + indent
                           + "onPayload: kvmemQueryHook(options.provider, model, options)")
    return ('import { kvmemQueryHook } from "./' + WRAPPER_NAME + '";\n'
            + patched).encode()


def wrapper_source(route: dict[str, str]) -> bytes:
    return (
        "// Generated by scripts/install_dsh_query_hook.py; no runtime credentials.\n"
        'import { kvmemQueryEpochPayload } from "./' + HOOK_NAME + '";\n'
        "const route = Object.freeze(" + json.dumps(route, ensure_ascii=False, sort_keys=True) + ");\n"
        "export function kvmemQueryHook(provider, model, options) {\n"
        "  return kvmemQueryEpochPayload(provider, model, options, route);\n"
        "}\n"
    ).encode()


def plan(root: Path, route: dict[str, str]) -> tuple[dict, dict[Path, bytes]]:
    if root.is_symlink() or root.resolve() != ALLOWED_HARNESS_ROOT.resolve():
        raise ValueError("Refusing to patch anything except the isolated cloud dsh-harness")
    root = root.resolve()
    if not root.is_dir():
        raise ValueError("Isolated DSH harness is not installed")
    index = find_adapter(root)
    state, backup = root / STATE_NAME, root / BACKUP_NAME
    hook, wrapper = index.parent / HOOK_NAME, index.parent / WRAPPER_NAME
    for path in (state, backup, hook, wrapper):
        plain_file(path)
        owned(path, root)
    original = backup.read_bytes() if backup.exists() else index.read_bytes()
    if digest(original) != EXPECTED_ADAPTER_SHA256:
        raise ValueError("Official adapter SHA256 mismatch; refusing to patch unknown code")
    hook_bytes = HOOK_SOURCE.read_bytes()
    patched, wrapper_bytes = patch_adapter(original), wrapper_source(route)
    expected = {
        "schema_version": 1,
        "adapter_path": str(index.relative_to(root)),
        "adapter_version": EXPECTED_ADAPTER_VERSION,
        "cli_version": EXPECTED_CLI_VERSION,
        "original_sha256": EXPECTED_ADAPTER_SHA256,
        "adapter_sha256": digest(patched),
        "hook_sha256": digest(hook_bytes),
        "wrapper_sha256": digest(wrapper_bytes),
        "route": route,
    }
    files = {backup: original, hook: hook_bytes, wrapper: wrapper_bytes, index: patched}
    if state.exists():
        if json.loads(state.read_text()) != expected:
            raise ValueError("Existing installation has a different route/source; refusing implicit replacement")
        if not backup.exists() or any(not p.exists() or p.read_bytes() != b for p, b in files.items()):
            raise ValueError("Installed Query hook was modified; refusing to overwrite it")
        return {"status": "unchanged", **expected}, {}
    if index.read_bytes() not in (original, patched):
        raise ValueError("Adapter differs from the official source and the requested patch")
    for path in (backup, hook, wrapper):
        if path.exists() and path.read_bytes() != files[path]:
            raise ValueError(f"Refusing to overwrite an unowned or different helper: {path.name}")
    # The adapter is replaced after both imported helpers. An interrupted first
    # install can resume only when every existing byte matches this exact plan.
    missing = {p: b for p, b in files.items() if not p.exists() or p.read_bytes() != b}
    missing[state] = (json.dumps(expected, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode()
    return {"status": "installed", **expected}, missing


def atomic_write(path: Path, content: bytes) -> None:
    mode = stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o644
    fd, temporary = tempfile.mkstemp(prefix="." + path.name + ".", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as out:
            out.write(content)
            out.flush()
            os.fsync(out.fileno())
        os.chmod(temporary, mode)
        # Atomic replacement avoids changing pnpm's shared content-addressed
        # source through an installed hard link.
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def install(harness_root: Path, route: dict | None = None, *, dry_run: bool = False) -> dict:
    route = normalize_route(DEFAULT_ROUTE if route is None else route)
    result, writes = plan(harness_root, route)
    if dry_run or not writes:
        return {**result, "status": "would_install" if dry_run and writes else result["status"],
                "dry_run": dry_run, "files_to_write": len(writes)}
    root = harness_root.resolve()
    lock = root / (STATE_NAME + ".lock")
    plain_file(lock)
    descriptor = os.open(lock, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    with os.fdopen(descriptor, "a") as guard:
        fcntl.flock(guard, fcntl.LOCK_EX)
        result, writes = plan(root, route)
        for path, content in writes.items():
            atomic_write(path, content)
    return {**result, "dry_run": False, "files_to_write": len(writes)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--harness-root", type=Path, default=ALLOWED_HARNESS_ROOT)
    parser.add_argument("--provider")
    parser.add_argument("--model")
    parser.add_argument("--base-url")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    values = (args.provider, args.model, args.base_url)
    if any(v is not None for v in values) and not all(v is not None for v in values):
        parser.error("--provider, --model, and --base-url must be supplied together")
    route = ({"provider": args.provider, "model": args.model, "baseURL": args.base_url}
             if all(v is not None for v in values) else None)
    try:
        result = install(args.harness_root, route, dry_run=args.dry_run)
    except (OSError, ValueError) as exc:
        parser.exit(1, f"DSH Query hook: {exc}\n")
    print(json.dumps(result, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
